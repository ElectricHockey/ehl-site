test('player creation and tied scoring awards work with PostgreSQL', { skip: !connectionString }, async () => {
  const client = new Client({ connectionString, ssl: connectionString.includes('localhost') ? false : { rejectUnauthorized: false } });
  await client.connect();
  const db = {
    prepare(sql) {
      let n = 0;
      let query = sql.replace(/\?/g, () => `$${++n}`);
      if (/^\s*INSERT/i.test(query) && !/RETURNING/i.test(query)) query += ' RETURNING *';
      return {
        async get(...args) { return (await client.query(query, args)).rows[0]; },
        async all(...args) { return (await client.query(query, args)).rows; },
        async run(...args) { const result = await client.query(query, args); return { changes: result.rowCount, lastInsertRowid: result.rows[0]?.id }; },
      };
    },
  };
  const response = () => ({ code: 200, status(code) { this.code = code; return this; }, json(body) { this.body = body; return this; } });
  try {
    await client.query('BEGIN');
    await client.query(`
      CREATE TEMP TABLE players (id integer GENERATED BY DEFAULT AS IDENTITY, name text, team_id integer, position text, number integer, is_rostered integer, discord text, discord_id text, user_id integer);
      CREATE TEMP TABLE users (id integer, username text, position text);
      CREATE TEMP TABLE seasons (id integer PRIMARY KEY);
      CREATE TEMP TABLE games (id integer, season_id integer, playoff_series_id integer, status text);
      CREATE TEMP TABLE game_player_stats (game_id integer, player_name text, position text, goals integer, assists integer);
      CREATE TEMP TABLE season_awards (season_id integer, award_key text, player_name text, notes text, UNIQUE (season_id, award_key, player_name));
      INSERT INTO seasons VALUES (1);
      INSERT INTO games VALUES (1,1,NULL,'complete'), (2,1,NULL,'complete'), (3,1,1,'complete');
      INSERT INTO game_player_stats VALUES
        (1,'Alpha','C',2,1), (2,' ALPHA ','C',1,1),
        (1,'Beta','C',3,2), (3,'Other','C',10,10),
        (1,'Goalie','G',5,5);
      INSERT INTO season_awards VALUES (1,'rocket_richard','Manual','chosen by admin'), (1,'art_ross','alpha','manually entered');
    `);
    let handler;
    const ctx = vm.createContext({ db, requireOwner() {}, app: { post(_path, _auth, fn) { handler = fn; } } });
    vm.runInContext(server.slice(server.indexOf("app.post('/api/players',"), server.indexOf("app.delete('/api/players/:id'")), ctx);
    let res = response();
    await handler({ body: { name: ' New Player ', position: 'C', number: '12' } }, res);
    assert.equal(res.code, 201);
    assert.equal(res.body.name, 'New Player');
    res = response();
    await handler({ body: { name: 'new player', merge: true, discord: 'example' } }, res);
    assert.equal(res.body.merged, true);
    assert.equal((await client.query('SELECT discord FROM players')).rows[0].discord, 'example');

    vm.runInContext(server.slice(server.indexOf("app.post('/api/admin/awards/season/:seasonId/auto-compute'"), server.indexOf('\n});', server.indexOf("app.post('/api/admin/awards/season/:seasonId/auto-compute'")) + 4), ctx);
    for (let i = 0; i < 2; i++) {
      res = response();
      await handler({ params: { seasonId: '1' }, body: { awards: ['rocket_richard', 'art_ross'] } }, res);
      assert.equal(res.body.errors.length, 0);
      assert.equal(res.body.computed.length, 4);
    }
    const result = await client.query('SELECT award_key, player_name, notes FROM season_awards ORDER BY award_key, player_name');
    assert.equal(result.rows.length, 5);
    assert.deepEqual(result.rows.filter(r => r.award_key === 'rocket_richard').map(r => r.player_name), ['Alpha', 'Beta', 'Manual']);
    assert.deepEqual(result.rows.filter(r => r.award_key === 'art_ross').map(r => r.player_name).sort(), ['Beta', 'alpha']);
  } finally {
    await client.query('ROLLBACK');
    await client.end();
  }
});
